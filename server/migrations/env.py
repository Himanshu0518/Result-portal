"""Alembic environment script.

This file is executed by every alembic command.  It wires together:
  - the DATABASE_URL from our Settings (reads .env automatically)
  - SQLAlchemy's Base.metadata (autogenerate support)
  - SQLite-specific pragmas (WAL, foreign keys)

Add new model modules to the import block below when you create them so
autogenerate can detect their tables.
"""
from __future__ import annotations

import logging
from logging.config import fileConfig

from sqlalchemy import Connection, engine_from_config, event, pool, text

from alembic import context

# ── App imports ───────────────────────────────────────────────────────────────
# Settings — reads DATABASE_URL from .env so the URL never lives in alembic.ini
from app.config.env import settings

# Base — must import every model module so their tables are on metadata before
# autogenerate runs.  Add new modules here as the project grows.
from app.config.db import Base  # noqa: F401 — registers Base
import app.models.students      # noqa: F401 — registers Student table
import app.models.imports       # noqa: F401 — registers Import / ImportError tables

# ── Alembic config ────────────────────────────────────────────────────────────
config = context.config

# Wire Python logging from alembic.ini (keeps alembic's own log output tidy).
if config.config_file_name is not None:
    fileConfig(config.config_file_name)

logger = logging.getLogger("alembic.env")

# Point autogenerate at our metadata.
target_metadata = Base.metadata

# Inject the DATABASE_URL from settings so alembic.ini stays secret-free.
config.set_main_option("sqlalchemy.url", settings.DATABASE_URL)


# ── SQLite helpers ────────────────────────────────────────────────────────────

def _set_sqlite_pragmas(dbapi_conn, _connection_record) -> None:
    """Enable WAL mode and foreign-key enforcement for every SQLite connection."""
    cursor = dbapi_conn.cursor()
    cursor.execute("PRAGMA journal_mode=WAL")
    cursor.execute("PRAGMA foreign_keys=ON")
    cursor.close()


def _include_object(obj, name, type_, reflected, compare_to):
    """Tell autogenerate to ignore SQLite's internal tables."""
    if type_ == "table" and name.startswith("sqlite_"):
        return False
    return True


# ── Migration runners ─────────────────────────────────────────────────────────

def run_migrations_offline() -> None:
    """'Offline' mode: emit SQL to stdout without a live DB connection.

    Useful for reviewing what will run, or for generating a SQL script to
    hand to a DBA.  Run with:  uv run alembic upgrade head --sql
    """
    url = config.get_main_option("sqlalchemy.url")
    context.configure(
        url=url,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        include_object=_include_object,
        # Render CHECK constraints in autogenerated migrations.
        render_as_batch=True,          # required for SQLite ALTER TABLE support
        compare_type=True,             # detect column type changes
        compare_server_default=True,   # detect server_default changes
    )
    with context.begin_transaction():
        context.run_migrations()


def _run_migrations_with_connection(connection: Connection) -> None:
    """Shared configuration for the online runner."""
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        include_object=_include_object,
        render_as_batch=True,
        compare_type=True,
        compare_server_default=True,
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    """'Online' mode: connect to the database and run migrations immediately."""
    connectable = engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,  # no pooling needed for one-shot migration runs
    )

    # Apply SQLite pragmas for the migration connection too.
    if settings.DATABASE_URL.startswith("sqlite"):
        event.listen(connectable, "connect", _set_sqlite_pragmas)

    with connectable.connect() as connection:
        logger.info("Running migrations against: %s", settings.DATABASE_URL)
        _run_migrations_with_connection(connection)


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
